CREATE TABLE IF NOT EXISTS public.store_orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  store_id UUID NOT NULL REFERENCES public.stores (id) ON DELETE RESTRICT,
  customer_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  customer_email TEXT NOT NULL,
  customer_name TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  delivery_address TEXT NOT NULL,
  delivery_neighborhood TEXT NOT NULL,
  delivery_instructions TEXT NOT NULL DEFAULT '',
  payment_method TEXT NOT NULL CHECK (payment_method IN ('transferencia', 'efectivo')),
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'accepted', 'rejected', 'cancelled')),
  subtotal NUMERIC(14, 2) NOT NULL CHECK (subtotal > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  reviewed_at TIMESTAMPTZ,
  reviewed_by UUID REFERENCES auth.users (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS store_orders_customer_created_idx
  ON public.store_orders (customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS store_orders_store_status_created_idx
  ON public.store_orders (store_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.store_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id UUID NOT NULL REFERENCES public.store_orders (id) ON DELETE CASCADE,
  product_id UUID NOT NULL REFERENCES public.productos (id) ON DELETE RESTRICT,
  product_code TEXT NOT NULL,
  product_name TEXT NOT NULL,
  unit_price NUMERIC(14, 2) NOT NULL CHECK (unit_price > 0),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  line_total NUMERIC(14, 2) NOT NULL CHECK (line_total > 0),
  UNIQUE (order_id, product_id)
);

CREATE INDEX IF NOT EXISTS store_order_items_order_idx
  ON public.store_order_items (order_id);

ALTER TABLE public.store_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.store_order_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.store_orders, public.store_order_items
  FROM PUBLIC, anon, authenticated;
